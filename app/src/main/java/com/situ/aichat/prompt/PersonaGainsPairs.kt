/**
 * 一条反差配对（图纸 §4.0 锁定）。[tier] 1=双敏感拉扯 2=跨组反差 3=同组反差（数字即优先级，小者先出）。
 *
 * 命中条件由消费端判定：[sensitive] 全部处于「很敏感」且 [numb] 全部处于「不吃这套」。
 */
internal class GainPair(
    val id: String,
    val tier: Int,
    val sensitive: List<String>,
    val numb: List<String>,
    private val template: String,
) {
    /**
     * `{user}` 一律替换为 [userName]；返回值已含前导 `"- "` 与句号。
     *
     * 人称规矩（图纸 §4.1 锁定）：句中第二次以后回指用「他」、`「」` 引号内的「他」是她的内心独白——
     * 两者都写死在 [template] 里**不参与替换**（J4 / J6 / I1）。
     */
    fun render(userName: String): String = "- " + template.replace(USER_PLACEHOLDER, userName)
}

/** tier 1 声明助手：双敏感拉扯（sensitive 两项、numb 空）。 */
private fun t1(id: String, s1: String, s2: String, template: String) =
    GainPair(id, tier = 1, sensitive = listOf(s1, s2), numb = emptyList(), template = template)

/** tier 2 声明助手：跨组反差（一敏感 × 一无感）。 */
private fun t2(id: String, s: String, n: String, template: String) =
    GainPair(id, tier = 2, sensitive = listOf(s), numb = listOf(n), template = template)

/** tier 3 声明助手：同组反差（一敏感 × 一无感）。 */
private fun t3(id: String, s: String, n: String, template: String) =
    GainPair(id, tier = 3, sensitive = listOf(s), numb = listOf(n), template = template)

/**
